/** A recap text in [lang], its {placeholders} filled in from [vars]; the German one where a language lacks it. */
fun recapText(lang: Lang, key: String, vars: Map<String, Any> = emptyMap()): String {
    val table = when (lang) {
        Lang.De -> RecapDe
        Lang.It -> RecapIt
        Lang.En -> RecapEn
    }
    var s = table[key] ?: RecapDe[key] ?: key
    for ((k, v) in vars) s = s.replace("{$k}", v.toString())
    return s
}
